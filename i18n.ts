export type I18nKey = keyof typeof en;

export function getLang(): "en" | "es" {
    return settings.store.language === "en" ? "en" : "es";
}

export function t(key: I18nKey): string {
    return (getLang() === "en" ? en : es)[key];
}

export const tabLabel = (type: MediaType) => t(`tab_${type}` as I18nKey);
export const sectionLabel = (type: MediaType) => t(`section_${type}` as I18nKey);
export const searchLabel = (type: MediaType) => t(`search_${type}` as I18nKey);
